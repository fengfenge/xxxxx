'''
模型定义，w1,w2,w3为需要学习的权重参数
目标是：通过训练让这些参数接近真实值[2,3,4]
'''
def func(x):
    y =  w1 * x**2 + w2 * x + w3
    return y

'''
损失函数定义，用于计算模型预测值与真实值的差异
衡量预测值和真实值的差异，越小越好，说明模型预测越准确
使用的是均方误差(MSE)损失函数
'''
def loss(y_pred, y_true):
    return (y_pred - y_true) ** 2


# 权重随机初始化
# 无初始权重，模型无法进行前向传播计算预测值。
# 无法计算损失函数和梯度，训练过程无法启动
# 不当的初始值可能导致梯度下降算法无法收敛，或者收敛速度过慢
# 如果所有权重初始化为相同值，会导致神经元学习相同的特征，无法区分不同的样本
# 破坏模型的表达能力，无法学习复杂模式
'''
模型的表达能力（Expressive Power）是指：
- 模型能够学习和表示复杂函数关系的能力
- 能够拟合多样化数据模式的能力
- 能够捕捉数据中非线性关系的能力
'''
#影响梯度流动 ：
#- 初始值过大可能导致梯度爆炸
#- 初始值过小可能导致梯度消失
#- 合适的初始化范围确保梯度正常流动
w1, w2, w3 = 1,0,-1

# 学习率设置
lr = 0.1

#batch size
batch_size = 100

# 训练过程，训练1000轮，每次训练batch_size个样本
for epoch in range(1000):
    epoch_loss = 0
    grad_w1 = 0
    grad_w2 = 0
    grad_w3 = 0
    counter = 0

    #zip(X, Y) ：将输入特征数组 X 和真实标签数组 Y 按索引位置配对，返回一个元组列表
    # 例如：zip(X, Y) = [(0.0, 4.0), (0.01, 4.0302), (0.02, 4.0608), ...]
    # zip() 是 Python 的 内置函数 ，用于将多个可迭代对象（如列表、元组等）按索引位置配对，返回一个迭代器。
    # zip(*iterables)，- 参数 ：一个或多个可迭代对象 - 返回值 ：返回一个迭代器，产生元组，每个元组包含来自每个输入可迭代对象的元素
    # 每个元组包含一个样本的特征值和真实标签
    #for i, (x, y_true) in enumerate(zip(X, Y)):
    #print(f"样本 {i}: x={x}, y={y_true}")
    for x, y_true in zip(X, Y):
        y_pred = func(x)

        # 在梯度下降算法中具有累积损失值的意义
        # 损失值累积：epoch_loss存储当前训练轮次（epoch）的总损失值，用于计算平均损失
        # 评估模型性能 ：通过累积所有样本的损失，得到整个数据集的总损失
        # 计算平均损失 ：后续通过 epoch_loss = epoch_loss/len(X) 计算平均损失
        epoch_loss += loss(y_pred, y_true)
        counter += 1
        #梯度计算，对w1,w2,w3求梯度，求偏导数
        grad_w1 += 2 * (y_pred - y_true) * x ** 2
        grad_w2 += 2 * (y_pred - y_true) * x 
        grad_w3 += 2 * (y_pred - y_true) 
        if counter == batch_size:
            #权重更新，根据梯度下降公式，更新w1,w2,w3，使用mini-batch梯度下降法sgd
            #sgd：随机梯度下降，每次更新一个样本的梯度，更新权重时，使用该样本的梯度
            #batch size：每次训练的样本数量，batch size越大，训练速度越快，但是模型的稳定性越差
            #学习率：lr，控制每次更新权重的步长，lr越大，更新权重的步长越大，但是模型的稳定性越差
            #梯度下降公式：w = w - lr * grad_w
            #grad_w：对w的梯度，求偏导数
            ## 1. 数学原理
### 为什么需要平均
# - 梯度方向稳定 ：平均梯度可以减少噪声，使更新方向更稳定
# - 学习率一致性 ：无论批次大小如何，学习率的效果保持一致
# - 数学正确性 ：与损失函数的定义（平均损失）保持一致

## 技术意义
# 1. 尺度一致性 ：
   
#    - 无论批次大小如何，学习率的尺度保持一致
#    - 避免批次大小变化时需要调整学习率
# 2. 数值稳定性 ：
   
#    - 防止梯度值过大导致的数值问题
#    - 保持梯度在合理范围内
# 3. 理论正确性 ：
   
#    - 与损失函数的数学定义一致
#    - 确保优化目标是最小化平均损失
            w1 = w1 - lr * grad_w1/batch_size   #sgd 
            w2 = w2 - lr * grad_w2/batch_size
            w3 = w3 - lr * grad_w3/batch_size
            counter = 0
            #梯度清零，准备下一次训练
            grad_w1 = 0
            grad_w2 = 0
            grad_w3 = 0
    # 计算当前轮的损失值
    # 在一个训练周期内，计算所有样本的损失值，取平均值作为当前轮的损失值
    # 标准化 ：消除样本数量对损失值的影响，使得不同大小的数据集可以比较
    # 可读性 ：使损失值更符合直觉，方便理解模型的训练过程，便于评估模型性能
    
    # - 监控训练进度 ：每轮输出平均损失，观察模型是否收敛
    # - 调参依据 ：根据平均损失的变化趋势调整学习率等超参数
    # - 早停机制 ：当平均损失低于阈值时停止训练，避免过拟合 
    epoch_loss =  epoch_loss/len(X)
    print("第%d轮， loss %f" %(epoch, epoch_loss))
    #早停机制 ：当loss < 0.00001时提前停止训练
    if epoch_loss < 0.00001:
        break

