# 求导说明：
# 对损失函数 ：(y_pred  - y_true) ** 2，求w1的梯度
# 链式法则
# 令 u = y_pred  - y_true， 即损失函数为 = u ** 2
# 所以根据链式法则，w1的导函数为 = 2u * du/dw1 （对w1的偏导数）
# 因为 u = y_pred  - y_true = w1 * x**2 +  w2 *x + 4 - y_true
# 所以 du/dw1 = x ** 2  (除w1外，其他字母都看做常数，常数导数为0)
# 所以导函数 = 2u * x ** 2
# 同理可得w2,w3的导函数
# 所以梯度 = [2u * x ** 2, 2u * x, 2u]