#!/bin/bash
#
# Rocky Linux 9 - Kubernetes 集群一键安装脚本
# 请把如下变量的值修改为实际环境中用于部署 Kubernetes 集群的主机的 IP 地址;
MASTER_IP='192.168.1.10'
NODE_01_IP='192.168.1.11'
NODE_02_IP='192.168.1.12'
NODE_03_IP='192.168.1.13'

# ============================================================
# Step 1: 生成 Ansible Inventory
# ============================================================
cat > hosts <<EOF
[k8s_master]
${MASTER_IP} node_ip=${MASTER_IP}

[k8s_node]
${NODE_01_IP} node_ip=${NODE_01_IP}
${NODE_02_IP} node_ip=${NODE_02_IP}
${NODE_03_IP} node_ip=${NODE_03_IP}

[k8s_cluster:children]
k8s_master
k8s_node
EOF

echo "=========================================="
echo "  Ansible Inventory 已生成 (hosts)"
echo "=========================================="
cat hosts

# ============================================================
# Step 2: 环境初始化 (YUM源/工具/SELinux/SWAP/IPVS/内核/Containerd)
# ============================================================
echo ""
echo "=========================================="
echo "  Step 1/4: 环境初始化"
echo "=========================================="
ansible-playbook -i hosts k8s-env-setup.yaml -l k8s_cluster

# ============================================================
# Step 3: 重启节点使配置生效
# ============================================================
echo ""
echo "=========================================="
echo "  Step 2/4: 重启节点使配置生效"
echo "=========================================="
ansible-playbook -i hosts reboot-system.yaml

# ============================================================
# Step 4: 安装 kubeadm / kubelet / kubectl
# ============================================================
echo ""
echo "=========================================="
echo "  Step 3/4: 安装 Kubernetes 组件"
echo "=========================================="
ansible-playbook -i hosts install-kubeadm.yaml

# ============================================================
# Step 5: 初始化集群 + Calico CNI + Join
# ============================================================
echo ""
echo "=========================================="
echo "  Step 4/4: 初始化集群并加入节点"
echo "=========================================="
ansible-playbook -i hosts ansible-install-kube-calico.yaml

echo ""
echo "=========================================="
echo "  ✅ Kubernetes 集群安装完成!"
echo "=========================================="
